# Converts --from-block into a concrete block number.
# It accepts two types of input:
# "latest" / "current": uses the current block number
# "<number>": converts the string into a number
def block_number_arg(w3: Web3, value: str) -> int:
    if value in {"latest", "current"}:
        return w3.eth.block_number

    return int(value)


# Reads BitcoinLiquidityCheckRequested events from the LendingPool contract
def get_request_logs(lending_pool: Any, from_block: int, to_block: int) -> list[Any]:
    event = lending_pool.events.BitcoinLiquidityCheckRequested()

    try:
        return event.get_logs(from_block=from_block, to_block=to_block)
    except TypeError:
        return event.get_logs(fromBlock=from_block, toBlock=to_block)


# For each event, creates a unique key to avoid processing it more than once
def event_key(event: Any) -> Tuple[str, int]:
    tx_hash = event["transactionHash"]

    if hasattr(tx_hash, "hex"):
        tx_hash = tx_hash.hex()

    return str(tx_hash), int(event["logIndex"])


# Updates the BitcoinOracle contract
def update_oracle(
    w3: Web3,
    chain_id: int,
    oracle: Any,
    trusted_oracle: LocalAccount,
    btc_address: str,
    balance: int,
    force: bool,
) -> None:
    
    # Checks whether there is already a registered balance
    already_recorded = oracle.functions.hasBtcBalanceRecord(btc_address).call()

    # If it already exists and force is not passed, does not update it
    if already_recorded and not force:
        current = oracle.functions.btcBalanceInSatoshi(btc_address).call()
        print(f"Oracle already recorded {btc_address}: {fmt_sat(current)}")
        return

    # If an update is needed, it sends a transaction
    send_tx(
        w3=w3,
        chain_id=chain_id,
        account=trusted_oracle,
        function_call=oracle.functions.setBtcBalance(btc_address, balance),
        label="BitcoinOracle.setBtcBalance",
    )

    # Reads the equivalent value in wei using the logic of the BitcoinOracle contract
    value_wei = oracle.functions.btcValueInWei(btc_address).call()

    print(f"Oracle updated: {btc_address}")
    print(f"  balance: {fmt_sat(balance)}")
    print(f"  value:   {value_wei} wei ({wei_to_eth(value_wei)} ETH)")


# Scans blocks from from_block to to_block and searches for BitcoinLiquidityCheckRequested
def scan_once(
    w3: Web3,
    chain_id: int,
    lending_pool: Any,
    oracle: Any,
    trusted_oracle: LocalAccount,
    balances: Dict[str, int],
    from_block: int,
    to_block: int,
    processed: set[Tuple[str, int]],
    force: bool,
) -> int:
    if to_block < from_block:
        return from_block

    logs = get_request_logs(lending_pool, from_block, to_block)

    # If it does not find events
    if not logs:
        print(f"No oracle requests from block {from_block} to {to_block}")
        return to_block + 1

    print(f"Found {len(logs)} oracle request(s) from block {from_block} to {to_block}")

    # If there are events
    for event in logs:
        key = event_key(event)

        if key in processed:
            continue

        processed.add(key)

        # Extracts applicant and btc_address
        applicant = event["args"]["applicant"]
        btc_address = event["args"]["btcAddress"]

        # Searches BTC balances (if the address is not in the dataset, it considers the balance 0)
        balance = balances.get(btc_address, 0)

        print("\nBitcoinLiquidityCheckRequested")
        print(f"  applicant:  {applicant}")
        print(f"  btcAddress: {btc_address}")
        print(f"  balance:    {fmt_sat(balance)}")

        update_oracle(
            w3=w3,
            chain_id=chain_id,
            oracle=oracle,
            trusted_oracle=trusted_oracle,
            btc_address=btc_address,
            balance=balance,
            force=force,
        )

    return to_block + 1


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Compact Bitcoin oracle service")

    parser.add_argument("--setup", default=SETUP_FILE)
    parser.add_argument("--chaindata", default=CHAINDATA_DIR)
    parser.add_argument("--cache", default=CACHE_FILE)
    parser.add_argument("--fallback-balances", default=FALLBACK_BALANCES_FILE)
    parser.add_argument("--bitcoin-network", choices=["mainnet", "testnet", "regtest"], default="mainnet")
    parser.add_argument("--rebuild-cache", action="store_true")
    parser.add_argument("--from-block", default="latest") # Starts from the last block
    parser.add_argument("--poll-interval", type=int, default=10)
    parser.add_argument("--once", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--top", type=int, default=0, help="Print top N BTC balances and continue") # Prints the BTC addresses with the highest balances
    parser.add_argument(
        "--max-blocks",
        type=int,
        default=DEFAULT_MAX_BLOCKS,
        help="Maximum number of Bitcoin blocks to parse from blk*.dat files. Default: 131000.",
    )

    return parser.parse_args()


def main() -> None:
    args = parse_args()

    # Loads initial_setup.json
    setup = load_json(Path(args.setup))

    # Loads or builds BTC balances
    balances = load_or_build_balances(args)

    # args.top is used to print the Bitcoin addresses with the highest balances
    if args.top > 0:
        print(f"\nTop {args.top} balances:")
        for i, (address, balance) in enumerate(
            sorted(balances.items(), key=lambda item: item[1], reverse=True)[: args.top],
            start=1,
        ):
            print(f"{i:>3}. {address:<45} {fmt_sat(balance)}")

    # Reads parameters of the private chain
    rpc_url = setup["network"]["rpc_url"] # url used by Python to connect to the local chain
    chain_id = int(setup["network"]["chain_id"])

    # Connects to the chain
    w3 = Web3(Web3.HTTPProvider(rpc_url))
    install_poa_middleware(w3)

    # Checks connection
    if not w3.is_connected():
        raise ConnectionError(f"Could not connect to {rpc_url}")

    # Checks chain id
    if w3.eth.chain_id != chain_id:
        raise RuntimeError(f"Unexpected chain id {w3.eth.chain_id}, expected {chain_id}")

    # Loads contracts
    lending_pool = contract_from_artifact(
        w3,
        "LendingPool",
        setup["contracts"]["LendingPool"],
    )

    oracle = contract_from_artifact(
        w3,
        "BitcoinOracle",
        setup["contracts"]["BitcoinOracle"],
    )

    # Loads trusted oracle account
    trusted_oracle = account_from_setup(setup, "trustedOracle")

    # Checks that the trusted oracle in the setup file is the same as the one saved in the contract
    onchain_trusted_oracle = oracle.functions.trustedOracle().call()

    if Web3.to_checksum_address(onchain_trusted_oracle) != Web3.to_checksum_address(
        trusted_oracle.address
    ):
        raise RuntimeError("trustedOracle in setup file does not match BitcoinOracle.trustedOracle()")

    print("\nConnected to private chain")
    print(f"RPC URL:       {rpc_url}")
    print(f"Chain ID:      {chain_id}")
    print(f"LendingPool:   {lending_pool.address}")
    print(f"BitcoinOracle: {oracle.address}")
    print(f"trustedOracle: {trusted_oracle.address}")
    print(f"trustedOracle balance: {wei_to_eth(w3.eth.get_balance(trusted_oracle.address))} ETH")

    next_from = block_number_arg(w3, args.from_block)
    processed: set[Tuple[str, int]] = set()

    print("\nOracle service started")
    print(f"Starting from block: {next_from}")

    try:
        while True:
            latest = w3.eth.block_number

            next_from = scan_once(
                w3=w3,
                chain_id=chain_id,
                lending_pool=lending_pool,
                oracle=oracle,
                trusted_oracle=trusted_oracle,
                balances=balances,
                from_block=next_from,
                to_block=latest,
                processed=processed,
                force=args.force,
            )

            if args.once:
                print("\nOne-shot scan completed")
                return

            time.sleep(args.poll_interval)

    except KeyboardInterrupt:
        print("\nOracle service stopped by user.")
        return


if __name__ == "__main__":
    main()
