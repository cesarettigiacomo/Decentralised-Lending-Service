# Reads demo BTC balances from JSON and returns a map, or raises an error if a balance is negative (when blk data is not available)
# Instead of recreating the real balance by reading the Bitcoin blockchain, it reads predefined balances
def load_fallback_balances(path: Path) -> Dict[str, int]:
    if not path.exists():
        return {}

    data = load_json(path)
    raw = data.get("balances", data)

    balances: Dict[str, int] = {}

    for address, value in raw.items():
        balance = int(value)

        if balance < 0:
            raise ValueError(f"Negative BTC balance for {address}: {balance}")

        balances[str(address)] = balance

    return balances


# load_cache and save_cache are useful to avoid loading blk*.dat every time. They save a cache file
def load_cache(path: Path) -> Dict[str, int]:
    data = load_json(path)
    raw = data.get("balances", data)

    return {
        str(address): int(balance)
        for address, balance in raw.items()
        if int(balance) > 0
    }


def save_cache(path: Path, balances: Dict[str, int], stats: Dict[str, int]) -> None:
    save_json(
        path,
        {
            "source": "blk.dat",
            "unit": "satoshi",
            "stats": stats,
            "balances": balances,
        },
    )


# Prepares python-bitcoinlib to read Bitcoin data correctly
def select_bitcoin_params(network: str) -> Tuple[Any, Any, Any]:

    # Imports necessary items
    try:
        from bitcoin import SelectParams
        from bitcoin.core import CBlock, b2lx
        from bitcoin.wallet import CBitcoinAddress
    except ImportError as exc:
        raise ImportError(
            "python-bitcoinlib is required for blk.dat parsing.\n"
            "Install it with: python3 -m pip install python-bitcoinlib"
        ) from exc

    # Selects the correct network
    # Bitcoin has multiple networks with different addresses
    # mainnet: real local Bitcoin network
    # testnet: public test network
    # regtest: local test network
    SelectParams(network)

    # Returns classes and functions for parsing
    # CBlock: deserializes a raw Bitcoin block
    # b2lx: converts Bitcoin binary hashes into readable strings
    # CBitcoinAddress: Obtains a Bitcoin address from an output script
    return CBlock, b2lx, CBitcoinAddress


# Tries to return an address from a scriptPubKey
def extract_address(script_pub_key: Any, CBitcoinAddress: Any) -> Optional[str]:  # Optional means that it can be a string or None
    try:
        return str(CBitcoinAddress.from_scriptPubKey(script_pub_key))
    except Exception:
        return None


# Reads a blk file; every block has the following structure:
# magic bytes | size | payload

# Reads 4 magic bytes, then 4 size bytes, then a payload of size bytes
# Returns the payload
def iter_blk_payloads(path: Path) -> Iterable[bytes]:
    with path.open("rb") as f:
        while True:
            magic = f.read(4) # Magic bytes identify the type or format of data (e.g., a Bitcoin block in a specific network)

            if not magic:
                return

            raw_size = f.read(4)

            if len(raw_size) != 4:
                return

            size = int.from_bytes(raw_size, "little")

            if size <= 0:
                return

            payload = f.read(size)

            if len(payload) != size:
                return

            yield payload


# Builds BTC balances starting from the blocks
# For each block, for each transaction:
# Removes old spent outputs
# Adds newly created outputs
def build_balances_from_blk(
    chaindata: Path,
    bitcoin_network: str,
    max_blocks: int,
) -> Tuple[Dict[str, int], Dict[str, int]]: # Returns two dictionaries: balances and stats
    CBlock, b2lx, CBitcoinAddress = select_bitcoin_params(bitcoin_network)

    blk_files = sorted(chaindata.glob("blk*.dat"))

    if not blk_files:
        raise FileNotFoundError(f"No blk*.dat files found in {chaindata}")

    # balances: address -> total balance in satoshi
    balances: Dict[str, int] = {}

    # utxos: (txid, output_index) -> (address, amount)
    utxos: Dict[Tuple[str, int], Tuple[str, int]] = {}

    # stats tracks parsing statistics for debugging and cache metadata
    stats = {
        "blocks": 0,
        "transactions": 0,
        "outputs_indexed": 0,
        "outputs_spent": 0,
        "outputs_skipped": 0,
    }

    print(f"Parsing {len(blk_files)} blk*.dat file(s) from {chaindata}")

    # For each blk*.dat file
    # With enumerate, it obtains file_index and the blk_file path
    for file_index, blk_file in enumerate(blk_files, start=1):
        print(f"[{file_index}/{len(blk_files)}] {blk_file}")

        # Extracts each serialized block payload from the blk.dat file.
        for payload in iter_blk_payloads(blk_file):
            if max_blocks > 0 and stats["blocks"] >= max_blocks:
                print(f"Reached max block limit: {max_blocks}")
                balances = {
                    address: balance
                    for address, balance in balances.items()
                    if balance > 0
                }
                return balances, stats

            try:
                block = CBlock.stream_deserialize(io.BytesIO(payload))
            # Skip malformed or unreadable block payloads
            except Exception:
                stats["outputs_skipped"] += 1
                continue

            stats["blocks"] += 1

            # For each block.vtx (list of block transactions)
            for tx in block.vtx:
                stats["transactions"] += 1

                # Mark spent outputs
                for txin in tx.vin:
                    key = (b2lx(txin.prevout.hash), int(txin.prevout.n))

                    if key in utxos:
                        address, amount = utxos.pop(key)
                        balances[address] = balances.get(address, 0) - amount
                        stats["outputs_spent"] += 1

                        if balances[address] <= 0:
                            balances.pop(address, None)

                txid = b2lx(tx.GetHash())

                # Index new standard outputs
                for output_index, txout in enumerate(tx.vout):
                    amount = int(txout.nValue)
                    address = extract_address(txout.scriptPubKey, CBitcoinAddress)

                    if amount <= 0 or address is None:
                        stats["outputs_skipped"] += 1
                        continue
                    
                    # For each output of the transaction:
                    # Finds amount
                    # Finds the address
                    # If it's valid, adds UTXO
                    # Updates balance
                    utxos[(txid, output_index)] = (address, amount)
                    balances[address] = balances.get(address, 0) + amount
                    stats["outputs_indexed"] += 1

    balances = {
        address: balance
        for address, balance in balances.items()
        if balance > 0
    }

    return balances, stats


# Decides how to build balances. If there are blk files, builds them from those files; otherwise, uses JSON
def load_or_build_balances(args: argparse.Namespace) -> Dict[str, int]:
    # Takes paths from the command line
    chaindata = Path(args.chaindata)
    cache = Path(args.cache)
    fallback = Path(args.fallback_balances)

    # Checks if the folder chaindata exists and if it contains blk*.dat files
    has_blk_files = chaindata.exists() and bool(list(chaindata.glob("blk*.dat")))

    # Reuses cached balances if available, unless rebuilding was requested.
    if has_blk_files:
        if cache.exists() and not args.rebuild_cache:
            print(f"Loading cached BTC balances from {cache}")
            balances = load_cache(cache)

        # If no cache exists, or --rebuild-cache was passed, parse blk*.dat files again
        else:
            balances, stats = build_balances_from_blk(
                chaindata=chaindata,
                bitcoin_network=args.bitcoin_network,
                max_blocks=args.max_blocks,
            )

            # Stores the computed balances so future runs can avoid reparsing blk*.dat files
            save_cache(cache, balances, stats)
            print(f"Saved BTC balance cache to {cache}")
            print(f"Stats: {stats}")

        print(f"Loaded {len(balances)} BTC balances from blk.dat/cache")
        return balances

    balances = load_fallback_balances(fallback)

    # If there are no blk*.dat files and no fallback balances, there are no sources from which to obtain Bitcoin balances
    if not balances:
        raise FileNotFoundError(
            f"No blk*.dat files found in {chaindata} and no fallback balances found in {fallback}"
        )

    print(
        f"No blk*.dat files found in {chaindata}.\n"
        f"Using fallback balances from {fallback}.\n"
        "This validates the oracle event/update flow, but not real blk.dat parsing."
    )
    print(f"Loaded {len(balances)} fallback BTC balances")

    return balances


