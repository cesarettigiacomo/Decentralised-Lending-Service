#!/usr/bin/env python3
"""
Compact off-chain Bitcoin oracle service

Primary mode:
  - read local Bitcoin blk*.dat files;
  - reconstruct a simple UTXO set;
  - compute BTC balances per address;
  - listen for LendingPool.BitcoinLiquidityCheckRequested events;
  - update BitcoinOracle.setBtcBalance(...).

Fallback mode:
  - if no blk*.dat files are available, load balances from a JSON file.
  - this keeps the demo executable when the assignment materials do not include
    Bitcoin block files.

Run from hardhat/:

  python3 oracle/oracle_service.py --from-block latest

Scan past requests once:

  python3 oracle/oracle_service.py --from-block 0 --once

Rebuild blk.dat cache:

  python3 oracle/oracle_service.py --rebuild-cache --once

Dependencies:

  python3 -m pip install web3 eth-account python-bitcoinlib
"""

from __future__ import annotations

import argparse
import io
import json
import time
from decimal import Decimal
from pathlib import Path
from typing import Any, Dict, Iterable, Optional, Tuple

from eth_account import Account
from eth_account.signers.local import LocalAccount
from web3 import Web3


SETUP_FILE = "deployments/initial_setup.json"
CHAINDATA_DIR = "../chaindata"
CACHE_FILE = "../data/btc_balances_from_blk_cache.json"
FALLBACK_BALANCES_FILE = "../data/btc_balances.json"

# ARTIFACTS indicates where to find the JSON files generated by Hardhat after the contracts are compiled
ARTIFACTS = {
    "LendingPool": "artifacts/contracts/LendingPool.sol/LendingPool.json",
    "BitcoinOracle": "artifacts/contracts/BitcoinOracle.sol/BitcoinOracle.json",
}

SATOSHI_PER_BTC = 100_000_000
DEFAULT_MAX_BLOCKS = 131_000


# ---------------------------------------------------------------------------
# Generic helpers
# ---------------------------------------------------------------------------

# Reads a JSON file and transforms it into a Python dictionary
def load_json(path: Path) -> Dict[str, Any]:
    if not path.exists():
        raise FileNotFoundError(f"File not found: {path}")

    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


# Saves a Python dictionary in a JSON file
def save_json(path: Path, data: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2), encoding="utf-8")


# Converts from wei to ETH
def wei_to_eth(value: int) -> Decimal:
    return Web3.from_wei(value, "ether")


# Converts from satoshi to BTC
def satoshi_to_btc(value: int) -> Decimal:
    return Decimal(value) / Decimal(SATOSHI_PER_BTC)


# Formats BTC balance for printing
def fmt_sat(value: int) -> str:
    return f"{value} satoshi ({satoshi_to_btc(value)} BTC)"


# Recovers the signed transaction in raw format
def raw_signed_transaction(signed: Any) -> bytes:
    return getattr(signed, "rawTransaction", None) or getattr(signed, "raw_transaction")


# Adds middleware needed to interact with local private chains
def install_poa_middleware(w3: Web3) -> None:
    try:
        from web3.middleware import ExtraDataToPOAMiddleware

        w3.middleware_onion.inject(ExtraDataToPOAMiddleware, layer=0)
    except Exception:
        try:
            from web3.middleware import geth_poa_middleware

            w3.middleware_onion.inject(geth_poa_middleware, layer=0)
        except Exception:
            pass


# Takes the private key from initial_setup.json and creates a Web3 account to sign transactions
def account_from_setup(setup: Dict[str, Any], name: str) -> LocalAccount:
    return Account.from_key(setup["accounts"][name]["private_key"])


# Creates a Web3 object starting from the address and the ABI of the contract
def contract_from_artifact(w3: Web3, name: str, address: str) -> Any:
    artifact = load_json(Path(ARTIFACTS[name]))

    return w3.eth.contract(
        address=Web3.to_checksum_address(address),
        abi=artifact["abi"],
    )


# Builds, signs and sends an Ethereum transaction
def send_tx(
    w3: Web3,
    chain_id: int,
    account: LocalAccount,
    function_call: Any,
    label: str,
    value: int = 0,
) -> Any:
    
    # Building the transaction
    tx = function_call.build_transaction(
        {
            "from": account.address,
            "nonce": w3.eth.get_transaction_count(account.address),
            "chainId": chain_id,
            "gasPrice": w3.eth.gas_price,
            "value": value,
        }
    )

    # Estimates gas cost
    tx["gas"] = int(w3.eth.estimate_gas(tx) * 1.25)

    # Signs the transaction
    signed = Account.sign_transaction(tx, account.key)

    # Sends the transaction
    tx_hash = w3.eth.send_raw_transaction(raw_signed_transaction(signed))

    # Waiting for the transaction to be mined
    receipt = w3.eth.wait_for_transaction_receipt(tx_hash)

    if receipt.status != 1:
        raise RuntimeError(f"{label} failed: {tx_hash.hex()}")

    print(f"{label:<34} tx={tx_hash.hex()} gasUsed={receipt.gasUsed}")
    return receipt


